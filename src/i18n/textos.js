/** Prefixo de rota por idioma: pt → '', en → '/en' */
export function prefixo(lang) {
  return lang === 'en' ? '/en' : '';
}

/** Constrói um link interno no idioma certo. L('/shop') → '/en/shop' quando lang=en */
export function link(lang, path) {
  if (lang !== 'en') return path;
  if (path === '/') return '/en/';
  return '/en' + path;
}
